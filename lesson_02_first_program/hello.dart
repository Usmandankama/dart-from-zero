// Lesson 2 · Install Dart and run your first program
//
// Run it:   dart run lesson_02_first_program/hello.dart

// Every Dart program starts here, in main. The lines between the curly
// braces run from top to bottom.
void main() {
  print('Hello, Dart!');
  print("I'm learning to code."); // Double quotes, because of the apostrophe.

  // Two slashes make a comment. Dart ignores it, so it's a note for people.
  print('Every line ends with a semicolon.');
}
